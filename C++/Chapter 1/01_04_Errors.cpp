/*
    Compilation error --> A compilation error in C++ is an error detected by the compiler during the 
    compilation process due to violation of syntax or language rules, which prevents the successful 
    creation of an executable program.
*/

/*
    Runtime error -->A runtime error is an error that occurs during the execution of 
    a program due to invalid operations such as division by zero, illegal memory access, or 
    infinite recursion, causing abnormal program termination.
*/